"""
Generate src/ReplicatedStorage/Shared/Config/RaidBossAssets.luau from the Blender rig metadata
(assets/models/raid/<boss>/<Boss>.json) and the uploaded asset ids (assets/models/raid/raid_asset_ids.json).

raid_asset_ids.json maps every mesh object name (e.g. "HollowKing_Torso") to
{ "MeshId": "rbxassetid://...", "TextureId": "rbxassetid://..." } as read from the imported model in Studio.
Run:  python tools/make_raid_boss_assets.py
"""
import json, os

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
RAID = os.path.join(REPO, "assets", "models", "raid")
OUT = os.path.join(REPO, "src", "ReplicatedStorage", "Shared", "Config", "RaidBossAssets.luau")
BOSSES = [("HOLLOW_KING", "hollow_king", "HollowKing"), ("THOUSAND_EYED", "thousand_eyed", "ThousandEyed"),
          ("BROODMOTHER", "broodmother", "Broodmother"), ("SHARDBOUND", "shardbound", "Shardbound")]


def v3(v):
    return "Vector3.new(%s, %s, %s)" % tuple(("%g" % round(x, 3)) for x in v)


def c3(c):
    return "Color3.fromRGB(%d, %d, %d)" % tuple(c)


def main():
    ids_path = os.path.join(RAID, "raid_asset_ids.json")
    ids = json.load(open(ids_path)) if os.path.exists(ids_path) else {}
    lines = [
        "--!strict",
        "-- GENERATED by tools/make_raid_boss_assets.py from assets/models/raid/*/<Boss>.json and raid_asset_ids.json.",
        "-- Do not hand-edit: regenerate after re-exporting or re-uploading the raid boss meshes.",
        "-- Studs, Roblox axes, model faces -Z, origin at the ground under the model's centre.",
        "-- Pivot = the joint (Motor6D) position; Centre/Size = the mesh's bounding box (the importer recentres meshes).",
        "",
        "export type Glow = { Mesh: string, MeshId: string, Colour: Color3, Centre: Vector3, Size: Vector3 }",
        "export type Segment = { Name: string, Parent: string?, Pivot: Vector3, Mesh: string?, MeshId: string, TextureId: string,",
        "\tCentre: Vector3?, Size: Vector3?, Glow: { Glow } }",
        "export type Boss = { Model: string, Root: string, Height: number, Segments: { Segment } }",
        "",
        "local Assets = {}",
        "",
        "Assets.Bosses = {",
    ]
    for boss_id, folder, model in BOSSES:
        meta = json.load(open(os.path.join(RAID, folder, model + ".json")))
        lines.append(f"\t{boss_id} = {{")
        lines.append(f"\t\tModel = \"{model}\", Root = \"{meta['Root']}\", Height = {meta['Size'][1]},")
        lines.append("\t\tSegments = {")
        for s in meta["Segments"]:
            mesh = s.get("Mesh")
            mid = ids.get(mesh, {}) if mesh else {}
            parent = f"\"{s['Parent']}\"" if s["Parent"] else "nil"
            body = f"Mesh = \"{mesh}\", MeshId = \"{mid.get('MeshId', '')}\", TextureId = \"{mid.get('TextureId', '')}\", Centre = {v3(s['Centre'])}, Size = {v3(s['Size'])}," if mesh else "MeshId = \"\", TextureId = \"\","
            glows = []
            for g in s["Glow"]:
                gid = ids.get(g["Mesh"], {})
                glows.append(f"{{ Mesh = \"{g['Mesh']}\", MeshId = \"{gid.get('MeshId', '')}\", Colour = {c3(g['Colour'])}, Centre = {v3(g['Centre'])}, Size = {v3(g['Size'])} }}")
            lines.append(f"\t\t\t{{ Name = \"{s['Name']}\", Parent = {parent}, Pivot = {v3(s['Pivot'])}, {body}")
            lines.append(f"\t\t\t\tGlow = {{ {', '.join(glows)} }} }},")
        lines.append("\t\t},")
        lines.append("\t},")
    lines += [
        "} :: { [string]: Boss }",
        "",
        "-- True when every mesh of the boss has an uploaded MeshId (otherwise the stand-in rig is used).",
        "function Assets.HasMeshes(bossId: string): boolean",
        "\tlocal boss = Assets.Bosses[bossId]",
        "\tif not boss then return false end",
        "\tfor _, s in boss.Segments do",
        "\t\tif s.Mesh and s.MeshId == \"\" then return false end",
        "\t\tfor _, g in s.Glow do if g.MeshId == \"\" then return false end end",
        "\tend",
        "\treturn true",
        "end",
        "",
        "return Assets",
        "",
    ]
    open(OUT, "w", encoding="utf-8").write("\n".join(lines))
    missing = sum(1 for _, f, m in BOSSES for s in json.load(open(os.path.join(RAID, f, m + ".json")))["Segments"]
                  for n in ([s.get("Mesh")] if s.get("Mesh") else []) + [g["Mesh"] for g in s["Glow"]] if n not in ids)
    print(f"wrote {OUT} ({missing} meshes without ids)")


if __name__ == "__main__":
    main()

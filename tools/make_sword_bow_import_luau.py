"""
Writes tests/studio-sword-bow-import.luau from the Blender manifests:
    assets/artifacts/sword_shield/sword_shield_manifest.json  (tools/blender/generate_vanguard_swords.py)
    assets/artifacts/bow/bows_manifest.json                    (tools/blender/generate_marksman_bows.py)

Re-run after regenerating either batch:  python tools/make_sword_bow_import_luau.py
"""

import json
import os
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SOURCES = [
    os.path.join(REPO, "assets", "artifacts", "sword_shield", "sword_shield_manifest.json"),
    os.path.join(REPO, "assets", "artifacts", "bow", "bows_manifest.json"),
]
OUT = os.path.join(REPO, "tests", "studio-sword-bow-import.luau")


def v(p):
    return f"Vector3.new({p[0]:.4f}, {p[1]:.4f}, {p[2]:.4f})"


def entry(info):
    lines = [f'\t{info["id"]} = {{', f'\t\tType = "{info["type"]}", Tier = {info["tier"]}, Tris = {info["tris"]},']
    if info["type"] == "SWORD_SHIELD":
        lines.append(f'\t\tPoints = {{ Grip = {v(info["grip"])}, Tip = {v(info["tip"])}, Base = {v(info["base"])}, Core = {v(info["core"])}, '
                     f'ShieldMount = {v(info["shield_mount"])}, ShieldCentre = {v(info["shield_centre"])} }},')
    else:
        lines.append(f'\t\tPoints = {{ Grip = {v(info["grip"])}, Nock = {v(info["nock"])}, TipUpper = {v(info["tip_upper"])}, '
                     f'TipLower = {v(info["tip_lower"])}, Core = {v(info["core"])} }},')
    lines.append("\t\tParts = {")
    for name, p in info["parts"].items():
        c = p["color"]
        lines.append(f'\t\t\t{name} = {{ Centre = {v(p["centre"])}, Size = {v(p["size"])}, Assembly = "{p["assembly"]}", '
                     f'Material = Enum.Material.{p["material"]}, Color = Color3.fromRGB({c[0]}, {c[1]}, {c[2]}) }},')
    lines.append("\t\t},")
    lines.append("\t},")
    return "\n".join(lines)


TEMPLATE = r'''--!nocheck
-- tests/studio-sword-bow-import.luau  (GENERATED by tools/make_sword_bow_import_luau.py - do not hand-edit MANIFEST)
-- Studio (Edit mode) step of the SWORD_SHIELD and BOW artifact remodel. Run it from the command
-- bar, or through Studio MCP, after importing the FBX files in assets/artifacts/sword_shield/ and
-- assets/artifacts/bow/ into Workspace with the 3D Importer (one Model per file, parts kept
-- separate, named after the file). Any subset can be imported; missing ids are skipped.
--
-- For every imported weapon it:
--   * works out the importer's scale and axes by fitting the parts' centres to the manifest
--     (authored in Blender: 1 unit = 1 stud), and rescales the model to studs,
--   * groups OffhandShield (HandleS + Shield*) and HunterArrow (Arrow*) sub-models,
--   * welds every part to its assembly's primary part (the arrow rides on the bow Handle),
--   * adds the sockets the runtime expects (sword: Grip/Tip/Vfx*, shield: ShieldMount/
--     VfxShieldCenter, bow: Grip/Nock/TipUpper/TipLower/Vfx*), in the WeaponModelBuilder
--     conventions (sword Grip = EDGE_PLUS_X, shield mount rotated (0, 90, 0), bow Grip = identity),
--   * applies the manifest materials and WeaponVfx, and replaces ReplicatedStorage.Assets.Weapons.<id>,
--   * returns a report plus SWORD_MESH_DATA / BOW_MESH_DATA entries for WeaponModelBuilder.

local ReplicatedStorage = game:GetService("ReplicatedStorage")

local MANIFEST = {
%MANIFEST%
}

-- Set to e.g. { art_iron_broadsword = true } to process a subset; nil processes every imported id.
local ONLY: { [string]: boolean }? = nil

local PRIMARY = { [""] = "Handle", OffhandShield = "HandleS", HunterArrow = "ArrowShaft" }

local Assets = ReplicatedStorage:WaitForChild("Assets")
local weaponsFolder = Assets:FindFirstChild("Weapons")
if not weaponsFolder then
	weaponsFolder = Instance.new("Folder")
	weaponsFolder.Name = "Weapons"
	weaponsFolder.Parent = Assets
end
local combatVfx = Assets:FindFirstChild("CombatVfx")
local okVfx, WeaponVfx = pcall(require, combatVfx and combatVfx:FindFirstChild("WeaponVfx"))

-- Roblox authoring frame (the WeaponModelBuilder convention) -> Blender frame: (x, y, z) -> (x, -z, y)
local function toBlender(v: Vector3): Vector3
	return Vector3.new(v.X, -v.Z, v.Y)
end

-- The 24 proper rotations of the axes (signed permutations with determinant +1).
local ROTATIONS = {}
do
	local axes = { Vector3.xAxis, Vector3.yAxis, Vector3.zAxis }
	for i = 1, 3 do
		for j = 1, 3 do
			if j ~= i then
				for _, si in { 1, -1 } do
					for _, sj in { 1, -1 } do
						local a, b = axes[i] * si, axes[j] * sj
						table.insert(ROTATIONS, { a, b, a:Cross(b) }) -- images of Blender X, Y, Z
					end
				end
			end
		end
	end
end

local function apply(rot, v: Vector3): Vector3
	return rot[1] * v.X + rot[2] * v.Y + rot[3] * v.Z
end

local function fmt(v: Vector3): string
	return string.format("Vector3.new(%.4f, %.4f, %.4f)", v.X, v.Y, v.Z)
end

local report, swordDump, bowDump = {}, {}, {}

local function process(id: string, info)
	local source = workspace:FindFirstChild(id)
	if not source then
		table.insert(report, `MISSING {id}: not found in Workspace`)
		return
	end

	local parts: { [string]: MeshPart } = {}
	for _, d in source:GetDescendants() do
		if d:IsA("MeshPart") then
			-- Blender suffixes repeated object names (Handle.001); the part name is what precedes it.
			local name = string.match(d.Name, "^(%a+)") or d.Name
			if info.Parts[name] and not parts[name] then
				d.Name = name
				parts[name] = d
			end
		end
	end
	local handle = parts.Handle
	if not handle then
		table.insert(report, `SKIPPED {id}: no Handle MeshPart`)
		return
	end

	-- Fit importer axes and scale: imported offset from Handle = s * R(authored offset from Handle).
	local a0 = info.Parts.Handle.Centre
	local best, bestErr, bestScale = nil, math.huge, 1
	for _, rot in ROTATIONS do
		local num, den = 0, 0
		for name, part in parts do
			local a = apply(rot, info.Parts[name].Centre - a0)
			num += a:Dot(part.Position - handle.Position)
			den += a:Dot(a)
		end
		local s = if den > 1e-9 then num / den else 1
		if s > 0 then
			local err = 0
			for name, part in parts do
				local a = apply(rot, info.Parts[name].Centre - a0) * s
				err += ((part.Position - handle.Position) - a).Magnitude ^ 2
			end
			if err < bestErr then
				best, bestErr, bestScale = rot, err, s
			end
		end
	end

	local model = Instance.new("Model")
	model.Name = id
	local subModels = {}
	for name, part in parts do
		for _, c in part:GetChildren() do
			if c:IsA("JointInstance") or c:IsA("WeldConstraint") or c:IsA("Attachment") then
				c:Destroy()
			end
		end
		local assembly = info.Parts[name].Assembly
		if assembly ~= "" then
			if not subModels[assembly] then
				local m = Instance.new("Model")
				m.Name = assembly
				m.Parent = model
				subModels[assembly] = m
			end
			part.Parent = subModels[assembly]
		else
			part.Parent = model
		end
	end
	model.PrimaryPart = handle
	for assembly, m in subModels do
		m.PrimaryPart = parts[PRIMARY[assembly]]
	end
	model.Parent = workspace
	model:ScaleTo(model:GetScale() / bestScale)

	-- Authored Blender point -> object space of `primary` (after the rescale, 1 unit = 1 stud).
	local function localPoint(primary: BasePart, p: Vector3): Vector3
		local world = handle.Position + apply(best, p - a0)
		return primary.CFrame:PointToObjectSpace(world)
	end
	local function localVector(primary: BasePart, v: Vector3): Vector3
		return primary.CFrame:VectorToObjectSpace(apply(best, v))
	end
	-- An attachment at authored point p whose orientation in the Roblox authoring frame is `rot`.
	local function socket(primary: BasePart, name: string, p: Vector3, rot: CFrame?)
		local r = rot or CFrame.identity
		local attachment = Instance.new("Attachment")
		attachment.Name = name
		attachment.CFrame = CFrame.fromMatrix(
			localPoint(primary, p),
			localVector(primary, toBlender(r.RightVector)),
			localVector(primary, toBlender(r.UpVector)),
			localVector(primary, toBlender(-r.LookVector))
		)
		attachment.Parent = primary
		return attachment
	end

	for name, part in parts do
		local spec = info.Parts[name]
		part.Anchored = false
		part.CanCollide = false
		part.CanTouch = false
		part.CanQuery = false
		part.Massless = true
		part.CastShadow = false
		part.Material = spec.Material
		part.Color = spec.Color
		part.Transparency = if spec.Material == Enum.Material.Glass then 0.12 else 0
		local primary = parts[PRIMARY[spec.Assembly]] or handle
		if part ~= primary then
			local weld = Instance.new("WeldConstraint")
			weld.Part0 = primary
			weld.Part1 = part
			weld.Parent = primary
		end
	end
	if parts.ArrowShaft then -- the nocked arrow rides on the bow
		local weld = Instance.new("WeldConstraint")
		weld.Part0 = handle
		weld.Part1 = parts.ArrowShaft
		weld.Parent = handle
	end

	local pts = info.Points
	if info.Type == "SWORD_SHIELD" then
		socket(handle, "Grip", pts.Grip, CFrame.Angles(0, math.rad(-90), 0)) -- up = blade, look = edge (+X)
		socket(handle, "Tip", pts.Tip)
		socket(handle, "VfxTip", pts.Tip)
		socket(handle, "VfxBase", pts.Base)
		socket(handle, "VfxCore", pts.Core)
		local handleS = parts.HandleS
		if handleS then
			socket(handleS, "ShieldMount", pts.ShieldMount, CFrame.Angles(0, math.rad(90), 0))
			socket(handleS, "VfxShieldCenter", pts.ShieldCentre)
		end
	else
		socket(handle, "Grip", pts.Grip) -- up = upper limb, look = arrow flight (-Z)
		socket(handle, "Nock", pts.Nock)
		socket(handle, "TipUpper", pts.TipUpper)
		socket(handle, "TipLower", pts.TipLower)
		socket(handle, "VfxTip", pts.TipUpper)
		socket(handle, "VfxBase", pts.TipLower)
		socket(handle, "VfxCore", pts.Core)
		socket(handle, "VfxNock", pts.Nock)
	end

	if okVfx and WeaponVfx.Apply then
		pcall(WeaponVfx.Apply, model, info.Type, info.Tier, id)
	end

	local old = weaponsFolder:FindFirstChild(id)
	if old then
		old:Destroy()
	end
	model.Parent = weaponsFolder
	source:Destroy()

	-- Mesh data entry: every part relative to its assembly's primary, every socket relative to its parent.
	local lines = { `\t{id} = \{`, `\t\tRarityTier = {info.Tier},`, "\t\tParts = {" }
	local names = {}
	for name in parts do
		table.insert(names, name)
	end
	table.sort(names, function(x, y)
		local px, py = PRIMARY[info.Parts[x].Assembly] == x, PRIMARY[info.Parts[y].Assembly] == y
		if info.Parts[x].Assembly ~= info.Parts[y].Assembly then
			return info.Parts[x].Assembly < info.Parts[y].Assembly
		elseif px ~= py then
			return px
		end
		return x < y
	end)
	for _, name in names do
		local part = parts[name]
		local spec = info.Parts[name]
		local primary = parts[PRIMARY[spec.Assembly]] or handle
		local rel = primary.CFrame:ToObjectSpace(part.CFrame)
		local rx, ry, rz = rel:ToOrientation()
		table.insert(lines, string.format(
			'\t\t\t{ Name = "%s", Assembly = "%s", MeshId = "%s", Size = %s, Offset = %s, Rotation = %s, Material = Enum.Material.%s, Color = Color3.fromRGB(%d, %d, %d), Transparency = %s },',
			name, spec.Assembly, part.MeshId, fmt(part.Size), fmt(rel.Position),
			fmt(Vector3.new(math.deg(rx), math.deg(ry), math.deg(rz))), spec.Material.Name,
			math.round(spec.Color.R * 255), math.round(spec.Color.G * 255), math.round(spec.Color.B * 255),
			tostring(part.Transparency)
		))
	end
	table.insert(lines, "\t\t},")
	table.insert(lines, "\t\tSockets = {")
	for _, d in model:GetDescendants() do
		if d:IsA("Attachment") and d.Parent and d.Parent:IsA("BasePart") and not string.match(d.Name, "^Vfx_") then
			local rx, ry, rz = d.CFrame:ToOrientation()
			table.insert(lines, string.format('\t\t\t{ Name = "%s", Part = "%s", Position = %s, Rotation = %s },',
				d.Name, d.Parent.Name, fmt(d.Position), fmt(Vector3.new(math.deg(rx), math.deg(ry), math.deg(rz)))))
		end
	end
	table.insert(lines, "\t\t},")
	table.insert(lines, "\t},")
	table.insert(if info.Type == "SWORD_SHIELD" then swordDump else bowDump, table.concat(lines, "\n"))

	local residual = math.sqrt(bestErr / math.max(1, #names)) / bestScale
	table.insert(report, string.format("%s %s: %d parts, import scale %.4f, fit residual %.3f studs, %d tris authored",
		if residual < 0.05 then "OK" else "CHECK", id, #names, bestScale, residual, info.Tris))
end

for id, info in MANIFEST do
	if not ONLY or ONLY[id] then
		process(id, info)
	end
end

table.sort(report)
table.sort(swordDump)
table.sort(bowDump)
return table.concat(report, "\n")
	.. "\n\n-- SWORD_MESH_DATA --\n" .. table.concat(swordDump, "\n")
	.. "\n\n-- BOW_MESH_DATA --\n" .. table.concat(bowDump, "\n")
'''


def main():
    # Optional: --only id,id --out <path> writes a batch copy (Studio MCP calls have a size limit).
    argv = sys.argv[1:]
    only = set(argv[argv.index("--only") + 1].split(",")) if "--only" in argv else None
    out = argv[argv.index("--out") + 1] if "--out" in argv else OUT
    entries = []
    for path in SOURCES:
        with open(path, encoding="utf-8") as fh:
            data = json.load(fh)
        for wid in sorted(data):
            if not only or wid in only:
                entries.append(entry(data[wid]))
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(TEMPLATE.replace("%MANIFEST%", "\n".join(entries)))
    print(f"wrote {out} ({len(entries)} weapons)")


main()

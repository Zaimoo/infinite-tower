"""Build the portal frame in Blender and export its part transforms for Rojo."""
from pathlib import Path
from math import cos, sin, tau

import bpy

ROOT = Path(__file__).resolve().parents[2]
bpy.ops.wm.read_factory_settings(use_empty=True)
palette = {"Stone": (0.13, 0.10, 0.17), "Trim": (0.25, 0.47, 0.55), "Rune": (0.32, 0.87, 1.0)}
materials = {}
for role, rgb in palette.items():
    material = bpy.data.materials.new(role)
    material.diffuse_color = (*rgb, 1)
    materials[role] = material

pieces = []


def block(role, x, y, z, sx, sy, sz, roll=0):
    bpy.ops.mesh.primitive_cube_add(size=1, location=(x, -z, y))
    obj = bpy.context.object
    obj.name = role
    obj.dimensions = (sx, sz, sy)
    obj.rotation_euler.y = -roll
    obj.data.materials.append(materials[role])
    pieces.append((role, x, y, z, sx, sy, sz, roll))


block("Stone", 0, 0.28, 0, 10.8, 0.56, 4.4)
block("Trim", 0, 0.61, 0, 10.3, 0.18, 4)
for index in range(12):
    angle = tau * index / 12
    x, y = cos(angle), sin(angle)
    roll = angle + tau / 4
    block("Stone", x * 4.25, 5.2 + y * 4.25, 0, 2.42, 1.14, 1.38, roll)
    block("Trim", x * 4.05, 5.2 + y * 4.05, 0.73, 2.15, 0.36, 0.16, roll)
    block("Rune", x * 4.45, 5.2 + y * 4.45, 0.75, 0.32, 0.32, 0.19, roll + tau / 8)

for side in (-1, 1):
    block("Stone", side * 3.55, 1.04, 0, 2.45, 0.9, 3.2)
    block("Trim", side * 3.8, 1.68, 0.73, 0.48, 1.7, 0.54, side * 0.29)
block("Rune", 0, 10.15, 0.12, 0.75, 0.75, 0.75, tau / 8)

bpy.ops.wm.save_as_mainfile(filepath=str(ROOT / "assets/models/boss_portal.blend"), compress=True)
output = ROOT / "src/ServerScriptService/Combat/BossPortalGeometry.luau"
lines = [
    "--!strict",
    "-- Generated by tools/blender/generate_boss_portal.py.",
    "return {",
]
for role, x, y, z, sx, sy, sz, roll in pieces:
    lines.append(
        f'\t{{ Role = "{role}", Position = Vector3.new({x:.5g}, {y:.5g}, {z:.5g}), '
        f'Size = Vector3.new({sx:.5g}, {sy:.5g}, {sz:.5g}), Roll = {roll:.5g} }},'
    )
output.write_text("\n".join([*lines, "}", ""]), encoding="utf-8")
